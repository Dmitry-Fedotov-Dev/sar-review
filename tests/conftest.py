# -*- coding: utf-8 -*-
"""Общие условия для всех тестов.

Пока здесь одно, но важное: тесты не должны зависеть от того, сколько
места осталось на машине, где их запускают.
"""
import collections

import pytest

import sar_staging

Usage = collections.namedtuple("Usage", "total used free")


@pytest.fixture(autouse=True)
def plenty_of_disk(monkeypatch):
    """Свободного места «много» -- если тест не сказал иначе.

    ЗАЧЕМ. Временная папка (`sar_staging`) с 14.09.2026 отказывает в
    скачивании, когда на диске мало места: потолок папки задаётся
    человеком и до 100 ГБ, а рядом лежит база, которой нужно место под
    WAL. Проверка правильная, но у неё есть побочное действие на тесты:
    они оперируют гигабайтами, а живут во временной папке НАСТОЯЩЕЙ
    машины. Как только на ней стало тесно (на C: осталось 1,1 ГБ),
    девять тестов покраснели разом -- при том, что проверяемое поведение
    не менялось ни на строку.

    Тест, результат которого зависит от свободного места на машине, --
    сломанный тест того же рода, что и зависящий от порядка запуска: он
    проходит не потому, что код верен. Поэтому диск здесь фиксируем.

    Проверки самого ограничителя от этого не страдают: они подменяют
    disk_usage внутри себя (см. test_prefetch.py), а их monkeypatch
    применяется ПОСЛЕ этого и побеждает.
    """
    monkeypatch.setattr(sar_staging.shutil, "disk_usage",
                        lambda p: Usage(10 ** 12, 0, 10 ** 12))
